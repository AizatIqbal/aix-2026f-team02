-- PointNull translation memory for merchant-managed product/category labels.
-- Run once against the same Supabase PostgreSQL project used by backend/.env.

CREATE TABLE IF NOT EXISTS public.translation_memory (
    translation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_text VARCHAR(500) NOT NULL,
    normalized_source_text VARCHAR(500) NOT NULL,
    source_language VARCHAR(10) NOT NULL CHECK (source_language IN ('en', 'ko')),
    target_language VARCHAR(10) NOT NULL CHECK (target_language IN ('en', 'ko')),
    context VARCHAR(20) NOT NULL CHECK (context IN ('product', 'category', 'campaign', 'general')),
    translated_text VARCHAR(1000) NOT NULL,
    provider VARCHAR(50) NOT NULL DEFAULT 'mymemory',
    is_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_translation_memory_key UNIQUE (
        source_language, target_language, context, normalized_source_text
    ),
    CONSTRAINT ck_translation_memory_language_pair CHECK (source_language <> target_language)
);

CREATE INDEX IF NOT EXISTS idx_translation_memory_review
    ON public.translation_memory (target_language, is_verified, updated_at DESC);

